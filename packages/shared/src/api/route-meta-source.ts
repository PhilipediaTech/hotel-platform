import type { RouteContract } from './contract.ts';

// What the web client needs of a route at runtime (T-091b): no schemas. route-meta.ts is
// generated from API_ROUTES with this function (`npm run routes:meta`).

export interface RouteMeta {
  operationId: string;
  method: RouteContract['method'];
  path: string;
  /** Present (true) when the route takes a JSON body. */
  body?: true;
  propertyScoped?: true;
  idempotent?: true;
  ifMatch?: true;
  produces?: RouteContract['produces'];
}

export function routeMetaOf(route: RouteContract): RouteMeta {
  return {
    operationId: route.operationId,
    method: route.method,
    path: route.path,
    ...(route.body ? { body: true as const } : {}),
    ...(route.propertyScoped ? { propertyScoped: true as const } : {}),
    ...(route.idempotent ? { idempotent: true as const } : {}),
    ...(route.ifMatch ? { ifMatch: true as const } : {}),
    ...(route.produces ? { produces: route.produces } : {}),
  };
}

/** The source of route-meta.ts for these routes (stable order: as listed). */
export function routeMetaSource(routes: Record<string, RouteContract>): string {
  const lines = Object.entries(routes).map(
    ([key, route]) => `  ${key}: ${JSON.stringify(routeMetaOf(route))},`,
  );
  return [
    '// Generated by `npm run routes:meta` from API_ROUTES: do not edit.',
    "import type { RouteMeta } from './route-meta-source.ts';",
    '',
    'export const ROUTE_META: Record<string, RouteMeta> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}
